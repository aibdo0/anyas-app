function setupDuas() {

  const list = document.getElementById("duasList");

  if (!list) return;

  const duas = [
    {
      title: "دعاء الاستعانة",
      text: "اللهم أعني على ذكرك وشكرك وحسن عبادتك."
    },
    {
      title: "دعاء الهداية",
      text: "اللهم اهدني وسددني."
    },
    {
      title: "دعاء المغفرة",
      text: "رب اغفر لي وارحمني وتب علي إنك أنت التواب الرحيم."
    },
    {
      title: "دعاء الرزق",
      text: "اللهم ارزقني رزقًا حلالًا طيبًا واسعًا مباركًا فيه."
    },
    {
      title: "دعاء تفريج الهم",
      text: "اللهم إني أعوذ بك من الهم والحزن، وأعوذ بك من العجز والكسل، وأعوذ بك من الجبن والبخل، وأعوذ بك من غلبة الدين وقهر الرجال."
    },
    {
      title: "دعاء الدنيا والآخرة",
      text: "ربنا آتنا في الدنيا حسنة وفي الآخرة حسنة وقنا عذاب النار."
    },
    {
      title: "دعاء الثبات",
      text: "يا مقلب القلوب ثبت قلبي على دينك."
    },
    {
      title: "دعاء الوالدين",
      text: "رب ارحمهما كما ربياني صغيرًا."
    }
  ];

  list.innerHTML = "";

  duas.forEach(dua => {

    const card =
      document.createElement("article");

    card.className = "dua-card";

    card.innerHTML = `
      <h3>${dua.title}</h3>
      <p>${dua.text}</p>
    `;

    list.appendChild(card);

  });

}


// =====================================================
// تشغيل الأدعية
// =====================================================

document.addEventListener(
  "DOMContentLoaded",
  () => {
    setupDuas();
  }
);
